"""Catalogue publisher/observer and a durable FCM invalidation outbox.

Messages carry no listing details, account data, addresses or credentials. Devices
fetch the latest approved snapshot through the normal authenticated API. Normal
priority permits Android to defer background delivery while the device sleeps.
"""
import asyncio
import hashlib
import logging
import os
import threading
from concurrent.futures import ThreadPoolExecutor
from datetime import timedelta
from pathlib import Path
from uuid import UUID, uuid4

import httpx
from fastapi import APIRouter, Depends, HTTPException, Request
from google.auth.transport.requests import Request as GoogleAuthRequest
from google.oauth2 import service_account
from pydantic import BaseModel, ConfigDict, Field, field_validator
from sqlalchemy import delete, func, or_, select, update
from sqlalchemy.exc import IntegrityError

from .auth import session_account, transaction
from .db import Account, CatalogueEvent, PushDelivery, PushDevice, Session, iso, now

router = APIRouter(prefix='/api/push', tags=['Device updates'])
logger = logging.getLogger(__name__)
_credentials = None
_credential_key = None
_credential_lock = threading.Lock()


class CataloguePublisher:
    """Subject in the observer pattern; observers participate in the transaction."""
    def __init__(self):
        self._observers = []

    def subscribe(self, observer):
        self._observers.append(observer)

    def publish(self, db, entity_kind, entity_id, version):
        event = CatalogueEvent(id=str(uuid4()), entity_kind=entity_kind,
                               entity_id=entity_id, version=version)
        for observer in self._observers:
            observer(db, event)


def persist_notification(db, event):
    # This insert rolls back with the listing and audit if any write fails.
    db.add(event)


catalogue_publisher = CataloguePublisher()
catalogue_publisher.subscribe(persist_notification)


def configured():
    path = os.getenv('GOOGLE_APPLICATION_CREDENTIALS', '')
    return (os.getenv('PUSH_ENABLED', 'false').lower() == 'true'
            and bool(os.getenv('FIREBASE_PROJECT_ID', '').strip())
            and bool(path) and Path(path).is_file())


def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()


class Installation(BaseModel):
    model_config = ConfigDict(extra='forbid', hide_input_in_errors=True)
    installation_id: str = Field(min_length=36, max_length=36)

    @field_validator('installation_id')
    @classmethod
    def valid_installation(cls, value):
        try:
            parsed = UUID(value)
        except (ValueError, AttributeError):
            raise ValueError('Use the installation identifier generated by the app.') from None
        if parsed.version != 4:
            raise ValueError('Use the installation identifier generated by the app.')
        return str(parsed)


class DeviceRegistration(Installation):
    token: str = Field(min_length=20, max_length=4096)

    @field_validator('token')
    @classmethod
    def valid_token(cls, value):
        if any(character.isspace() for character in value):
            raise ValueError('The device registration token is invalid.')
        return value


@router.put('/device')
def register_device(body: DeviceRegistration, request: Request, account=Depends(session_account)):
    if account['role'] != 'REGISTERED_USER':
        raise HTTPException(403, 'Device updates are available in the user application.')
    from .main import throttle
    throttle(request, 'push-device-registration', 30)
    device_id, token_digest = digest(body.installation_id), digest(body.token)
    try:
        with transaction() as db:
            # Token rotation and signing in to a different account rebind this app
            # installation. A token must have only one delivery destination.
            db.execute(delete(PushDevice).where(PushDevice.token_digest == token_digest, PushDevice.id != device_id))
            device = db.get(PushDevice, device_id)
            if device:
                device.account_id, device.token = account['id'], body.token
                device.token_digest, device.updated_at = token_digest, now()
            else:
                db.add(PushDevice(id=device_id, account_id=account['id'], token=body.token,
                                  token_digest=token_digest, updated_at=now()))
    except IntegrityError:
        raise HTTPException(409, 'Device registration changed. Please retry.') from None
    return {'registered': True, 'push_configured': bool(configured())}


@router.delete('/device')
def unregister_device(body: Installation, account=Depends(session_account)):
    with transaction() as db:
        db.execute(delete(PushDevice).where(PushDevice.id == digest(body.installation_id),
                                           PushDevice.account_id == account['id']))
    return {'registered': False}


def access_token():
    global _credentials, _credential_key
    path = Path(os.environ['GOOGLE_APPLICATION_CREDENTIALS'])
    key = (str(path), path.stat().st_mtime_ns)
    with _credential_lock:
        if _credential_key != key:
            _credentials = service_account.Credentials.from_service_account_file(
                path, scopes=['https://www.googleapis.com/auth/firebase.messaging'])
            _credential_key = key
        if not _credentials.valid or (_credentials.expiry and
                _credentials.expiry.replace(tzinfo=None) <= now().replace(tzinfo=None) + timedelta(minutes=5)):
            _credentials.refresh(GoogleAuthRequest())
        return _credentials.token


def _claim_event():
    instant, lease = now(), str(uuid4())
    available = (CatalogueEvent.completed_at.is_(None), CatalogueEvent.next_attempt_at <= instant,
                 or_(CatalogueEvent.lease_until.is_(None), CatalogueEvent.lease_until < instant))
    with Session.begin() as db:
        event_id = db.scalar(select(CatalogueEvent.id).where(*available)
                             .order_by(CatalogueEvent.created_at, CatalogueEvent.id).limit(1))
        if not event_id:
            return None
        claimed = db.execute(update(CatalogueEvent).where(CatalogueEvent.id == event_id, *available)
                             .values(lease_token=lease, lease_until=instant + timedelta(minutes=5)))
        return (event_id, lease) if claimed.rowcount == 1 else None


def _prepare(event_id, lease):
    with Session.begin() as db:
        event = db.get(CatalogueEvent, event_id)
        if not event or event.lease_token != lease:
            return None
        if not event.prepared:
            devices = db.scalars(select(PushDevice.id).join(Account).where(
                Account.state == 'ACTIVE', Account.role == 'REGISTERED_USER',
                PushDevice.updated_at >= now() - timedelta(days=90))).all()
            db.add_all(PushDelivery(event_id=event_id, device_id=device_id) for device_id in devices)
            event.prepared = True
            db.flush()
        # A disabled account or a signed-out/deleted installation must no longer
        # receive pending updates. FK cascades handle explicit unregistration.
        inactive_devices = select(PushDevice.id).join(Account).where(
            or_(Account.state != 'ACTIVE', Account.role != 'REGISTERED_USER'))
        db.execute(delete(PushDelivery).where(PushDelivery.event_id == event_id,
                                              PushDelivery.device_id.in_(inactive_devices)))
        devices = db.execute(select(PushDevice.id, PushDevice.token, PushDevice.token_digest)
                             .join(PushDelivery).where(PushDelivery.event_id == event_id,
                                                       PushDelivery.next_attempt_at <= now())
                             .order_by(PushDevice.id).limit(100)).all()
        payload = {'type': 'catalogue_changed', 'event_id': event.id,
                   'entity_kind': event.entity_kind, 'entity_id': event.entity_id,
                   'version': str(event.version), 'published_at': iso(event.created_at)}
        return payload, [(row.id, row.token, row.token_digest) for row in devices]


def _send(client, endpoint, payload, device):
    device_id, token, token_digest = device
    try:
        response = client.post(endpoint, json={'message': {'token': token, 'data': payload,
            'android': {'priority': 'NORMAL', 'collapse_key': 'catalogue_changed', 'ttl': '86400s'}}})
        if response.is_success:
            return device_id, token_digest, 'sent'
        try:
            error = response.json().get('error', {})
            code = next((detail.get('errorCode') for detail in error.get('details', []) if detail.get('errorCode')), '')
        except (ValueError, AttributeError, TypeError):
            code = ''
        # Do not delete tokens for generic INVALID_ARGUMENT: it can also indicate
        # a message/configuration problem. Only unregistered tokens are definitive.
        return device_id, token_digest, 'unregistered' if code == 'UNREGISTERED' else f'HTTP_{response.status_code}'
    except httpx.HTTPError as error:
        return device_id, token_digest, type(error).__name__


def _finish(event_id, lease, results, error=None):
    with Session.begin() as db:
        event = db.get(CatalogueEvent, event_id)
        if not event or event.lease_token != lease:
            return
        failures = []
        for device_id, token_digest, result in results:
            device = db.get(PushDevice, device_id)
            delivery = db.get(PushDelivery, (event_id, device_id))
            if not device or not delivery:
                continue
            if device.token_digest != token_digest:
                delivery.next_attempt_at, delivery.attempts = now(), 0
                continue
            if result == 'sent':
                db.delete(delivery)
                event.delivered_count += 1
            elif result == 'unregistered':
                # A concurrent token refresh must survive an old token's failure.
                db.execute(delete(PushDevice).where(PushDevice.id == device_id,
                                                    PushDevice.token_digest == token_digest))
            else:
                failures.append(result)
                delivery.attempts += 1
                delivery.last_error = result
                delivery.next_attempt_at = now() + timedelta(seconds=min(3600, 60 * (2 ** min(delivery.attempts - 1, 6))))
        db.flush()
        pending = db.scalar(select(func.count()).select_from(PushDelivery).where(PushDelivery.event_id == event_id))
        event.lease_token = event.lease_until = None
        if not pending and not error:
            event.completed_at, event.last_error = now(), None
        else:
            failed = error or (failures[0] if failures else None)
            event.attempts += 1 if failed else 0
            event.last_error = failed
            # Individual failures wait without blocking the other devices. A
            # global credential/send failure retries the batch with backoff.
            event.next_attempt_at = (now() + timedelta(seconds=min(3600, 60 * (2 ** min(event.attempts - 1, 6))))
                                     if error else db.scalar(select(func.min(PushDelivery.next_attempt_at))
                                         .where(PushDelivery.event_id == event_id)))


def dispatch_pending():
    """Deliver one bounded batch; callable by the API's background observer loop."""
    if not configured():
        return 0
    claimed = _claim_event()
    if not claimed:
        return 0
    event_id, lease = claimed
    try:
        prepared = _prepare(event_id, lease)
        if prepared is None:
            return 0
        payload, devices = prepared
        if not devices:
            _finish(event_id, lease, [])
            return 0
        token = access_token()
        endpoint = 'https://fcm.googleapis.com/v1/projects/' + os.environ['FIREBASE_PROJECT_ID'].strip() + '/messages:send'
        with httpx.Client(timeout=10, headers={'Authorization': 'Bearer ' + token}) as client:
            with ThreadPoolExecutor(max_workers=8) as workers:
                results = list(workers.map(lambda device: _send(client, endpoint, payload, device), devices))
        _finish(event_id, lease, results)
        return sum(result[2] == 'sent' for result in results)
    except Exception as error:
        # Exception messages may contain credentials, token values or remote data.
        logger.warning('Catalogue push batch failed: %s', type(error).__name__)
        _finish(event_id, lease, [], type(error).__name__)
        return 0


async def run_dispatcher():
    while True:
        try:
            await asyncio.to_thread(dispatch_pending)
        except asyncio.CancelledError:
            raise
        except Exception as error:
            logger.warning('Catalogue push observer failed: %s', type(error).__name__)
        await asyncio.sleep(5)
